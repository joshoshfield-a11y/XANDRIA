/**
 * Graphics wave 2, workstream A — before/after beauty + perf shots for the
 * terrain detail pass (micro-detail normal layer, richer slope/height
 * bands, shoreline wetness, spawn/landmark wear).
 *
 * Deterministic scene: fixed-seed blobs from scripts/terrain-detail-specs.ts
 * (mountains, water, dusk + day) x quality tiers (high=desktop, standard=S25)
 * x viewports (desktop 1280x800, mobile 360x780).
 *
 * BEFORE=1 writes *-before.png (run from the base worktree); without it the
 * after shots land at the deliverable paths. Shots go to
 * $OUT_DIR (default tests/e2e/shots/terrain-detail).
 *
 * Gates: zero console/page errors, stream queue drained, draw calls +
 * frameMs captured per shot for the perf report.
 */
import { test, expect } from '@playwright/test';
import { readFileSync, mkdirSync } from 'node:fs';

const BEFORE = !!process.env.BEFORE;
const OUT = process.env.OUT_DIR ?? 'tests/e2e/shots/terrain-detail';
// Spec blobs: generated by scripts/terrain-detail-specs.ts into SPEC_DIR.
// (/tmp is ephemeral on this box — the script writes to the workspace dir.)
const SPEC_DIR = process.env.SPEC_DIR ?? '/tmp/terrain-detail-specs';
mkdirSync(OUT, { recursive: true });

const SCENES = [
  { tod: 'dusk', q: 'high', tier: 'desktop' },
  { tod: 'dusk', q: 'standard', tier: 's25' },
  { tod: 'day', q: 'high', tier: 'desktop' },
  { tod: 'day', q: 'standard', tier: 's25' },
] as const;

const VIEWPORTS = [
  { name: 'desktop', width: 1280, height: 800 },
  { name: 'mobile', width: 360, height: 780 },
];

const SHOTS = [
  { name: 'closeup', kind: 'closeup' },
  { name: 'slope', kind: 'slope' },
] as const;

test.describe('terrain-detail', () => {
  // generous budget: swiftshader boots a full chunked world per test, and
  // browser setup itself can be slow when the box is loaded
  test.setTimeout(600_000);

for (const s of SCENES) {
  for (const vp of VIEWPORTS) {
    test(`terrain-detail ${s.tod}/${s.tier}/${vp.name}${BEFORE ? ' (before)' : ''}`, async ({ page }) => {
      const errors: string[] = [];
      page.on('pageerror', (e) => errors.push('[pageerror] ' + e.message));
      page.on('console', (m) => { if (m.type() === 'error') errors.push('[console] ' + m.text()); });

      const b64 = readFileSync(`${SPEC_DIR}/${s.tod}-${s.q}.b64`, 'utf8').trim();
      await page.setViewportSize({ width: vp.width, height: vp.height });
      await page.goto(`/player.html?test=1&spec=${b64}`, { waitUntil: 'load' });
      await page.waitForFunction(() => (window as any).__XANDRIA__?.engine?.state === 'playing', null, { timeout: 300000 });
      await page.addStyleTag({ content: '.xhud{display:none!important}' });

      // verify the tier the engine actually settled on
      const q = await page.evaluate(() => (window as any).__XANDRIA__.engine.effectiveQuality());
      expect(q).toBe(s.q);

      // drain the chunk stream once per test (focus stays at spawn, so the
      // queue only drains — it never re-fills between shots)
      await page.waitForFunction(() => {
        const t = (window as any).__XANDRIA__?.engine?.terrain;
        return t && t.getStreamStats().queue === 0;
      }, null, { timeout: 600000 });
      await page.waitForTimeout(1500); // grade/fog settle

      for (const shot of SHOTS) {
        // Frame the shot. The stream focus stays at spawn for the whole
        // test: the full 1000m world is inside the 1500m mesh load radius,
        // so every chunk is resident after the initial drain — moving the
        // focus per shot would only churn physics bodies for no visual gain.
        // The third-person rig's camera mutators are neutralized (same
        // technique as maxsize-farfield.spec.ts) for deterministic framing.
        const m: any = await page.evaluate((kind) => {
          const X = (window as any).__XANDRIA__;
          const T = X.engine.terrain;
          // spawnXZ is workstream-A API; the base (before) build has no
          // Terrain.spawnXZ — fall back to (0,0), the default flat center.
          const sx = T.spawnXZ ? T.spawnXZ.x : 0, sz = T.spawnXZ ? T.spawnXZ.z : 0;
          let px: number, py: number, pz: number, tx: number, ty: number, tz: number;
          if (kind === 'closeup') {
            // 4m above the trampled spawn disc, looking down at the wear
            const gx = sx + 7, gz = sz + 9;
            const gy = T.heightAt(gx, gz);
            px = gx + 3.2; py = gy + 3.4; pz = gz + 4.2;
            tx = gx; ty = gy + 0.2; tz = gz;
          } else {
            // find the steepest mountainside near spawn (pure height
            // function — deterministic; scan stays inside the 512m scene)
            let best = { x: sx + 80, z: sz, slope: -1 };
            for (let a = 0; a < 16; a++) {
              for (let r = 40; r <= 200; r += 32) {
                const x = sx + Math.cos((a / 16) * Math.PI * 2) * r;
                const z = sz + Math.sin((a / 16) * Math.PI * 2) * r;
                const sl = T.slopeAt(x, z);
                if (sl > best.slope) best = { x, z, slope: sl };
              }
            }
            const gy = T.heightAt(best.x, best.z);
            const dx = best.x - sx, dz = best.z - sz;
            const dl = Math.hypot(dx, dz) || 1;
            px = best.x + (dx / dl) * 55; pz = best.z + (dz / dl) * 55;
            py = T.heightAt(px, pz) + 26;
            tx = best.x; ty = gy + 6; tz = best.z;
          }
          X.engine.streamFocus = new (X.engine.camera.position.constructor)(sx, 0, sz);
          const cam = X.engine.camera;
          cam.position.set(px, py, pz);
          cam.lookAt(tx, ty, tz);
          cam.updateProjectionMatrix();
          cam.position.copy = () => cam.position;
          cam.position.set = () => cam.position;
          const protoLookAt = Object.getPrototypeOf(cam).lookAt.bind(cam);
          cam.lookAt = () => protoLookAt(tx, ty, tz);
          const st = T.getStreamStats();
          return {
            queue: st.queue,
            draws: X.engine.perf.drawCalls,
            frameMs: X.engine.perf.frameMs,
            tris: X.engine.perf.triangles,
          };
        }, shot.kind);
        // stream already drained above; just let the frame settle, then measure
        await page.waitForTimeout(1200); // grade/fog settle
        const fin: any = await page.evaluate(() => {
          const X = (window as any).__XANDRIA__;
          return { draws: X.engine.perf.drawCalls, frameMs: X.engine.perf.frameMs, tris: X.engine.perf.triangles };
        });
        const tag = `${s.tod}-${s.tier}-${vp.name}-${shot.kind}${BEFORE ? '-before' : ''}`;
        await page.screenshot({ path: `${OUT}/${tag}.png`, timeout: 600_000 });
        console.log(
          `[terrain-detail] ${tag} draws=${fin.draws} frameMs=${fin.frameMs.toFixed(2)} ` +
          `tris=${(fin.tris / 1000).toFixed(0)}k queueAtFrame=${m.queue}`,
        );
        expect(m.queue).toBe(0);
      }
      expect(errors).toEqual([]);
    });
  }
}
});
